const OL_FIELDS = [
  'key', 'title', 'author_name', 'first_publish_year', 'number_of_pages_median',
  'cover_i', 'ratings_average', 'ratings_count', 'edition_count',
  'id_project_gutenberg', 'id_standard_ebooks', 'ebook_access', 'lending_identifier_s',
].join(',');

async function lookup([title, author]) {
  const url = `https://openlibrary.org/search.json?title=${encodeURIComponent(title)}&author=${encodeURIComponent(author)}&fields=${OL_FIELDS}&limit=3`;
  const res = await fetch(url, {
    headers: { 'User-Agent': 'incipit-catalog-script (prototype)' },
    signal: AbortSignal.timeout(30000),
  });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const { docs } = await res.json();

  return {
    seed: `${title} / ${author}`,
    candidates: docs.map((d) => ({
      key: d.key,
      title: d.title,
      author: d.author_name?.[0],
      year: d.first_publish_year,
      pages: d.number_of_pages_median,
      cover: d.cover_i,
      rating: d.ratings_average ? Number(d.ratings_average.toFixed(2)) : null,
      ratings: d.ratings_count ?? 0,
      editions: d.edition_count,
      gutenberg: d.id_project_gutenberg?.slice(0, 4),
      standardEbooks: d.id_standard_ebooks?.slice(0, 2),
      // 'borrowable' means the Internet Archive lends the edition named in `lend`.
      access: d.ebook_access,
      lend: d.lending_identifier_s,
    })),
  };
}

const filter = process.argv[2]?.toLowerCase();
const seeds = filter ? SEEDS.filter(([t]) => t.toLowerCase().includes(filter)) : SEEDS;

for (const seed of seeds) {
  try {
    console.log(JSON.stringify(await lookup(seed)));
  } catch (e) {
    console.log(JSON.stringify({ seed: seed.join(' / '), error: String(e) }));
  }
}
